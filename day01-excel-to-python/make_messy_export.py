"""Generate messy synthetic monthly sales exports, the way many sales systems dump them into Excel.
Company, customers, sales reps and prices are invented. Seeded: same cell values every run (see fingerprint.py).
Usage: python make_messy_export.py -> input/Sales_Export_2026-09.xlsx, input/Sales_Export_2026-10.xlsx, _answer_key/*.csv"""
import random, os, shutil, datetime as dt
import pandas as pd
from openpyxl import Workbook

SEED = 20261128
REGIONS = ["North", "South", "East", "West"]
VARIANTS = {r: [r, r.lower(), r.upper(), r + " ", " " + r, r[0] + ". Zone"] for r in REGIONS}
REPS = {"North": ["Asha Menon", "Vikram Rao"], "South": ["Lakshmi Iyer", "Arjun Nair"],
        "East": ["Priya Das", "Rahul Sen"], "West": ["Meera Shah", "Kabir Patel"]}       # fictional people
PRODUCTS = {"Steel Tiffin Box": 649.0, "Copper Water Bottle": 899.0, "Cotton Bedsheet Set": 1299.0,
            "Ceramic Mug Pair": 449.0, "LED Desk Lamp": 1499.0}
CUSTOMERS = [f"Retailer {c}" for c in "ABCDEFGHIJKLMNOPQRST"]
TARGETS = {"2026-09": {"North": 300000, "South": 260000, "East": 280000, "West": 320000},
           "2026-10": {"North": 330000, "South": 280000, "East": 300000, "West": 340000}}

def build(year, month, n, rnd, inv0):
    days = (dt.date(year + (month == 12), month % 12 + 1, 1) - dt.timedelta(days=1)).day
    rows = []
    for i in range(n):
        reg = rnd.choice(REGIONS); p = rnd.choice(list(PRODUCTS)); q = rnd.choice([1, 2, 2, 3, 4, 5, 6, 8, 10, 12])
        disc = rnd.choice([0, 0, 0, 0.05, 0.1, 0.15])
        rows.append(dict(invoice=f"INV-{inv0 + i}", date=dt.date(year, month, rnd.randint(1, days)), customer=rnd.choice(CUSTOMERS),
                         region=reg, rep=rnd.choice(REPS[reg]), product=p, qty=q, unit_price=PRODUCTS[p], discount=disc))
    for src in rnd.sample(rows, max(3, n // 40)):     # returns: credit notes with negative quantity
        r = dict(src); r["invoice"] = "CN-" + r["invoice"][4:]; r["qty"] = -rnd.randint(1, min(2, r["qty"])); rows.append(r)
    for r in rows: r["net"] = round(r["qty"] * r["unit_price"] * (1 - r["discount"]), 2)
    return rows

def messy(rows, ym, rnd, prev_rows):
    out = []
    for r in rows:
        d = r["date"]; s = rnd.random()
        dv = d if s < 0.6 else d.strftime("%d/%m/%Y") if s < 0.9 else d.isoformat()
        price = r["unit_price"] if rnd.random() < 0.7 else f"₹{r['unit_price']:,.2f}"
        net = r["net"] if rnd.random() < 0.7 else f"{r['net']:,.2f}"
        disc = r["discount"] if rnd.random() < 0.6 else f"{r['discount'] * 100:g}%"
        rep = r["rep"] if rnd.random() < 0.8 else rnd.choice([r["rep"].upper(), " " + r["rep"], r["rep"].lower() + " "])
        out.append([r["invoice"], dv, r["customer"], rnd.choice(VARIANTS[r["region"]]), rep, r["product"], r["qty"], price, disc, net])
    miss = rnd.sample(range(len(out)), 2)                              # unit price missing (never on a re-pasted row)
    miss_ids = [out[k][0] for k in miss]
    for k in miss: out[k][7] = None
    late = []
    for r in rnd.sample(prev_rows, 3) if prev_rows else []:   # late entries that belong to last month
        late.append([r["invoice"], r["date"], r["customer"], r["region"], r["rep"], r["product"], r["qty"], r["unit_price"], r["discount"], r["net"]])
    for x in late: out.insert(rnd.randint(0, len(out)), x)
    dups = [list(x) for x in rnd.sample([o for o in out if o[0] not in miss_ids], 5)]    # re-pasted rows
    for x in dups: out.insert(rnd.randint(0, len(out)), x)
    return out, late, miss_ids

def write(path, ym, out, targets):
    wb = Workbook(); ws = wb.active; ws.title = "Export"
    ws.append([f"Sales Register - Monsoon Home Goods (synthetic demo company)"]); ws.append([f"Period: {ym}   Generated by: ERP export"]); ws.append([])
    ws.append(["Invoice No ", "Invoice Date", "Customer", "Region", "Sales Rep", "Product", "Qty", "Unit Price", "Discount", "Net Amount"])
    rnd = random.Random(len(out))
    for i, r in enumerate(out):
        ws.append(r)
        if i % 37 == 36: ws.append([])                                   # blank rows
    tot = sum(float(str(r[9]).replace(",", "")) for r in out)            # what a plain SUM over the export gives
    ws.append([]); ws.append(["Grand Total", None, None, None, None, None, None, None, None, round(tot, 2)])
    for row in ws.iter_rows(min_row=5, min_col=2, max_col=2):
        for c in row:
            if isinstance(c.value, dt.date): c.number_format = "DD-MMM-YY"
    t = wb.create_sheet("Targets"); t.append(["Region", "Target (INR)"])
    for k, v in targets.items(): t.append([k, v])
    wb.save(path)

def main():
    rnd = random.Random(SEED)
    for d in ("input", "_answer_key"): shutil.rmtree(d, ignore_errors=True); os.makedirs(d)
    sep = build(2026, 9, 236, rnd, 50001); octo = build(2026, 10, 268, rnd, 50301)
    for ym, rows, prev in (("2026-09", sep, None), ("2026-10", octo, sep)):
        out, late, miss = messy(rows, ym, random.Random(SEED + int(ym[-2:])), prev)
        write(f"input/Sales_Export_{ym}.xlsx", ym, out, TARGETS[ym])
        t = pd.DataFrame(rows); t["status"] = t["invoice"].map(lambda i: "MISSING_PRICE" if i in miss else "CLEAN")
        t.to_csv(f"_answer_key/truth_{ym}.csv", index=False)
        print(f"{ym}: {len(rows)} true lines ({sum(r['qty'] < 0 for r in rows)} credit notes), {len(out)} exported rows incl. 5 re-pasted, {len(late)} late entries, {len(miss)} missing prices")

if __name__ == "__main__":
    main()
